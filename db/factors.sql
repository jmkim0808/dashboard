-- 단 주의: 아래 **전력 배출계수는 각국 고시가 이미 CO2 또는 CO2eq 로 환산한 값**이므로
-- 우리가 GWP 를 다시 적용하지 않는다. gwp_set 컬럼에는 그 고시가 사용한 기준을 기록한다.
-- AR6 는 Scope 1 연료 연소의 CH4·N2O 산정에 적용된다.
--
-- ### 전력 배출계수 — 국제 기준이 아니라 각국 공식 고시를 쓴다
--
-- 전력은 국가·지역별 발전 구성에 따라 값이 완전히 다르므로, 국제 표준값이 아니라
-- 해당 국가의 공식 고시값을 쓰는 것이 정확하고, 고객사·법정 보고도 그것을 요구한다.
-- IEA 도 국가별 값을 제공한다.
--
