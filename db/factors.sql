--
-- ### 온실가스 지구온난화지수(GWP)
--
-- **IPCC 제6차 평가보고서(AR6) 100년 기준을 채택한다.** CH4 27.9 · N2O 273.
-- GHG Protocol 은 가장 최근 IPCC 평가보고서 값 사용을 권고하며, CDP·CSRD·SBTi·ISSB 가
-- AR6 를 요구하는 추세다.
